def main():
    # 读取课程难度
    difficulties = {}
    for fname in ('init.sql', 'seed_1_math.sql', 'seed_2_cs.sql', 'seed_3_science.sql',
                  'seed_4_human.sql', 'seed_5_lang.sql', 'seed_6_art.sql'):
        path = os.path.join(REPO, fname)
        if not os.path.exists(path):
            path = os.path.join(REPO, 'SekaiLearning', fname)
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as f:
            text = f.read()
        for m in re.finditer(r"\((\d+),\s*(\d+),\s*'((?:[^']|'')*)',\s*'((?:[^']|'')*)',\s*'([^']*)',\s*(\d+),\s*(\d+),\s*(\d+)\)", text):
            cid = int(m.group(1))
            difficulties[cid] = m.group(5)

    lines = []
    lines.append('-- =============================================================')
    lines.append('-- 知识库扩充 Part8: 每门课程扩充至 100 节课 (sekai_learning_lessons)')
    lines.append('-- 图文并茂长文版: 由 seed/gen_lessons.py 生成, id 从 %d 起' % ID_BASE)
    lines.append('-- 使用 INSERT ... ON DUPLICATE KEY UPDATE, 重复执行可原地更新内容')
    lines.append('-- =============================================================')
    lines.append('')

    rid = ID_BASE
    total = 0
    row_lines = []
    for cid in sorted(COURSES):
        subject, name = COURSES[cid]
        topic = COURSE_TOPIC[cid]
        chapters = CHAPTERS[topic]
        diff_cycle = difficulties.get(cid, 'intermediate')
        rng = random.Random(cid * 131 + 7)
        rows = []
        # 1. 导学
        rows.append((0, ('special', SPECIALS[0])))
        # 2. 12 章 × 8 节
        for ci, chapter in enumerate(chapters):
            for k in range(8):
                idx = ci * 8 + k + 1
                aspect = SUBJECT[subject]['aspects'][(ci + k + cid) % len(SUBJECT[subject]['aspects'])]
                rows.append((idx, ('lesson', build_lesson(cid, name, subject, topic, idx, chapter, aspect, rng, diff_cycle))))
        # 3. 复习/练习/结课
        rows.append((97, ('special', SPECIALS[1])))
        rows.append((98, ('special', SPECIALS[2])))
        rows.append((99, ('special', SPECIALS[3])))

        for sort_idx, item in rows:
            if item[0] == 'special':
                # 特殊课: (title, intro, points)
                title, intro, pts = item[1]
                intro = intro.replace('{course}', name)
                content, summary, points, diff, minutes = build_special(
                    cid, sort_idx, name, diff_cycle, title, intro, pts, subject)
            else:
                title = item[1][0]
                content = item[1][1]
                summary = item[1][2]
                points = item[1][3]
                diff = item[1][4]
                minutes = item[1][5]
            title_e = sql_escape(title)
            content_e = sql_escape(content)
            summary_e = sql_escape(summary)
            points_e = sql_escape(json_keys(points))
            row_lines.append("(%d, %d, '%s', '%s', '%s', '%s', '%s', %d, %d)" % (
                rid, cid, title_e, content_e, summary_e, points_e, diff, minutes, 1000 + sort_idx))
            rid += 1
            total += 1

    # 分批 INSERT (每批 ~400 行, 避免超出 max_allowed_packet)
    CHUNK = 400
    for i in range(0, len(row_lines), CHUNK):
        chunk = row_lines[i:i + CHUNK]
        lines.append('')
        lines.append("INSERT INTO sekai_learning_lessons (id, course_id, title, content, summary, key_points, difficulty, estimated_minutes, sort_order) VALUES")
        lines.append(','.join(chunk))
        lines.append("ON DUPLICATE KEY UPDATE content=VALUES(content), summary=VALUES(summary), key_points=VALUES(key_points), estimated_minutes=VALUES(estimated_minutes);")

    # UPDATE 语句
    lines.append('')
    lines.append('-- 更新课程统计: 每门课 100 节, 约 20 小时')
    lines.append("UPDATE sekai_learning_courses SET lesson_count = 100, estimated_hours = 20;")
    lines.append('')

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('生成完成: %s (%d 节课)' % (OUT, total))

    # ---- 原有时长(id<100000)图文扩充: 追加配图 + 拓展阅读 + 思考练习 ----
    tsv = os.path.join(ROOT, 'original_lessons.tsv')
    if not os.path.exists(tsv):
        print('[skip] 未找到 original_lessons.tsv, 跳过原课时图文扩充')
        return
    orig = []
    with open(tsv, encoding='utf-8') as f:
        f.readline()  # header
        for line in f:
            parts = line.rstrip('\n').split('\t')
            if len(parts) >= 2 and parts[0].isdigit():
                orig.append((int(parts[0]), int(parts[1])))
    lines2 = []
    lines2.append('-- =============================================================')
    lines2.append('-- 知识库扩充 Part8b: 原有时长图文扩充 (追加配图/拓展阅读/思考练习)')
    lines2.append('-- 幂等: 已扩充的课时(content 含 <!--SEKAI-EXT-->) 不会重复追加')
    lines2.append('-- 由 seed/gen_lessons.py 生成, 依赖 seed_7_bilibili.sql 的课程封面图')
    lines2.append('-- =============================================================')
    lines2.append('')
    for lid, lcid in orig:
        rng = random.Random(lid * 31 + 5)
        s = SUBJECT[COURSES[lcid][0]]
        figs = lesson_figures(COURSES[lcid][0], '本节拓展', '知识理解', s['formulas'], 2)
        fig1 = figure_svg(figs[0][0], figs[0][1], '本节', '拓展学习', 1) if len(figs) > 0 else ''
        fig2 = figure_svg(figs[1][0], figs[1][1], '本节', '拓展学习', 2) if len(figs) > 1 else ''
        fact = s['facts'][rng.randrange(len(s['facts']))].format(course=COURSES[lcid][1], chapter='本节', aspect='拓展学习')
        fact2 = GENERIC_FACTS[rng.randrange(len(GENERIC_FACTS))].format(course=COURSES[lcid][1], chapter='本节', aspect='拓展学习')
        exp = GENERIC_EXPANDS[rng.randrange(len(GENERIC_EXPANDS))].format(course=COURSES[lcid][1], chapter='本节', aspect='拓展学习')
        qpool = GENERIC_QS + s['questions']
        q1 = qpool[rng.randrange(len(qpool))].format(course=COURSES[lcid][1], chapter='本节', aspect='拓展学习')
        append = '\n'.join([
            '<!--SEKAI-EXT-->',
            '<div style="margin-top:20px;padding:16px;border:1px solid rgba(255,255,255,.09);border-radius:12px;background:rgba(255,255,255,.03)">',
            '<p><b>📖 拓展学习</b></p>',
            fig1,
            '<p>' + fact + '</p>',
            '<p>' + fact2 + '</p>',
            fig2,
            '<p>' + exp + '</p>',
            '<p><b>🤔 思考与练习</b></p>',
            '- ' + q1,
            '- 结合本节内容，自拟一道练习题并给出解答。',
            '</div>',
        ])
        # 幂等且可替换旧版扩充: 已存在标记则先裁掉旧扩充块再追加新块
        lines2.append("UPDATE sekai_learning_lessons SET content = CONCAT(IF(content LIKE '%%<!--SEKAI-EXT-->%%', SUBSTRING_INDEX(content, '<!--SEKAI-EXT-->', 1), content), '%s') WHERE id = %d;" % (sql_escape(append), lid))
    out2 = os.path.join(ROOT, 'seed_8b_original_expand.sql')
    with open(out2, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines2))
    print('原课时图文扩充: %s (%d 节)' % (out2, len(orig)))

if __name__ == '__main__':
    main()
