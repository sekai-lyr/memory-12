def load_images():
    images = {}
    seed = os.path.join(ROOT, 'seed_7_bilibili.sql')
    if not os.path.exists(seed):
        print('[warn] 未找到 seed_7_bilibili.sql, 课时图片将缺失')
        return images
    row_re = re.compile(r"^\((\d+),\s*(\d+),\s*'((?:[^']|'')*)',\s*'((?:[^']|'')*)',\s*'((?:[^']|'')*)',")
    with open(seed, encoding='utf-8') as f:
        for line in f:
            m = row_re.match(line)
            if not m:
                continue
            cid = int(m.group(2))
            cover = m.group(5)
            if not cover:
                continue
            images.setdefault(cid, []).append((cover, m.group(3)))
    return images

IMAGES = load_images()

